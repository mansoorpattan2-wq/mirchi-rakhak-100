export function accountErrorMessage(error: unknown, lang: Lang) {
  const code = typeof error === "string" ? error : authErrorCode(error);
  const c = accountCopy[lang];
  if (
    [
      "auth/invalid-credential",
      "auth/wrong-password",
      "auth/user-not-found",
      "auth/invalid-login-credentials",
    ].includes(code)
  )
    return c.credentialsError;
  if (code === "auth/invalid-email") return c.invalidEmail;
  if (code === "auth/email-already-in-use") return c.emailUsed;
  if (["auth/weak-password", "auth/password-does-not-meet-requirements"].includes(code))
    return c.weakPassword;
  if (code === "auth/password-mismatch") return c.mismatch;
  if (code === "auth/network-request-failed") return c.networkError;
  if (code === "auth/too-many-requests") return c.tooMany;
  if (code === "auth/user-disabled") return c.disabled;
  if (["auth/operation-not-allowed", "auth/unauthorized-domain"].includes(code))
    return c.providerUnavailable;
  if (code === "auth/popup-blocked") return c.popupBlocked;
  if (["auth/popup-closed-by-user", "auth/cancelled-popup-request"].includes(code))
    return c.popupClosed;
  if (
    ["auth/configuration-not-found", "auth/invalid-api-key", "auth/app-not-authorized"].includes(
      code,
    )
  )
    return c.configuration;
  return c.genericError;
}
